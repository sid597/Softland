                tokenized-ir (token-matcher/tokenize-ir ir dt)
                ;; Step 3: compile to rt-node
                rt-node (compiler/compile-ir tokenized-ir dt {:use-tokens? true})]
            (json-response {:ok true
                            :ir tokenized-ir
                            :rt-node rt-node
