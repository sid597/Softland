            (log/error e "[EPISODE][BIRTH-ERROR]" {:uri uri})
            (edn-response 500 {:status :error :error (.getMessage e)})))
        (edn-response 405 {:error "Method not allowed. Use POST."}))

      ;; first-light A P2b — the geometry settle write: camera + block
