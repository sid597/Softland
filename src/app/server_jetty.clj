                                               (edn/read-string (slurp source-file)))
                                      ;; Check if .cljc file exists for shadcn
                                      cljc-file (io/file base-dir slug "shadcn.cljc")
                                      has-cljc? (.exists cljc-file)]
                                  (assoc comp
                                    :source source
                                    :has-cljc? has-cljc?)))
